def unit(value):
    return {"stringUnit": {"state": "translated", "value": value}}


def main():
    strings = {}
    for key, pt in sorted(PT.items()):
        if key in PLURALS:
            continue
        strings[key] = {"localizations": {"pt-PT": unit(pt)}}
    for key, forms in PLURALS.items():
        if forms is None:
            continue
        en_one, en_other, pt_one, pt_other = forms
        strings[key] = {"localizations": {
            "en": {"variations": {"plural": {"one": unit(en_one), "other": unit(en_other)}}},
            "pt-PT": {"variations": {"plural": {"one": unit(pt_one), "other": unit(pt_other)}}},
        }}
    catalog = {"sourceLanguage": "en", "strings": dict(sorted(strings.items())), "version": "1.0"}
    with open(OUT, "w", encoding="utf-8") as f:
        json.dump(catalog, f, ensure_ascii=False, indent=2, sort_keys=False)
        f.write("\n")
    print(f"Wrote {len(strings)} strings to {os.path.relpath(OUT, ROOT)}")


if __name__ == "__main__":
    main()
